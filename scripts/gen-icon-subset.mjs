/** 从源码中收集用到的 Iconify 图标，生成 ri 图标子集（减小打包体积） */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const srcDir = join(root, 'web/src')
const files = []
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    const st = statSync(p)
    if (st.isDirectory()) walk(p)
    else if (/\.(vue|ts|tsx|js|mjs)$/.test(name)) files.push(p)
  }
}
walk(srcDir)

const used = { ep: new Set(), ri: new Set() }
const re = /\b(ep|ri):([a-z0-9][a-z0-9-]*)/g
/** 收集图标：忽略文档里的占位写法（ep:xxx / ri:xxx） */
const collect = (text) => {
  let m
  re.lastIndex = 0
  while ((m = re.exec(text))) {
    if (m[2] === 'xxx') continue
    used[m[1]].add(m[2])
  }
}
for (const f of files) collect(readFileSync(f, 'utf8'))

// 后端菜单（migrations/*.up.sql 里登记的菜单/按钮图标）会直接下发给前端渲染，
// 这些值不在 web/src 里，必须单独扫描，否则新菜单的图标在离线图标集里缺失 → 渲染空白。
const migrationsDir = join(root, 'migrations')
try {
  for (const name of readdirSync(migrationsDir)) {
    if (!name.endsWith('.sql')) continue
    collect(readFileSync(join(migrationsDir, name), 'utf8'))
  }
} catch {
  /* migrations 目录缺失时忽略（例如只打包前端） */
}

// 后端菜单可能下发的 ep 图标（与 internal/service/route.go 的别名表保持一致时最稳妥）
const menuIcons = ['user','user-filled','avatar','menu','office-building','postcard','notebook','operation','setting','flag','folder','clock','timer','monitor','connection','cpu','tickets','odometer','home-filled','document','document-copy','list','edit','lock','tools','share','bell','link','trend-charts','coin','box','files','data-line','grid','calendar','message','pie-chart','histogram','finished','switch-button','set-up','guide','management','key','minus','search','plus','delete','refresh','upload','download','close','check','info-filled','warning-filled','circle-check','circle-close']
menuIcons.forEach((n) => used.ep.add(n))

const build = (prefix) => {
  const collection = JSON.parse(readFileSync(join(root, `web/node_modules/@iconify-json/${prefix}/icons.json`), 'utf8'))
  const icons = {}
  const missing = []
  for (const name of [...used[prefix]].sort()) {
    if (collection.icons[name]) icons[name] = collection.icons[name]
    else missing.push(name)
  }
  return {
    data: {
      prefix: collection.prefix,
      width: collection.width,
      height: collection.height,
      ...(collection.aliases ? { aliases: Object.fromEntries(Object.entries(collection.aliases).filter(([k]) => icons[k] || used[prefix].has(k))) } : {}),
      icons
    },
    count: Object.keys(icons).length,
    missing
  }
}

const ri = build('ri')
const ep = build('ep')
const out = join(srcDir, 'utils/ui/iconify-subset.ts')
writeFileSync(
  out,
  `/**\n * AUTO-GENERATED by scripts/gen-icon-subset.mjs — 请勿手改。\n * 源码中实际引用的 Iconify 图标子集（ep ${ep.count} 个 / ri ${ri.count} 个），用于离线打包。\n * 新增图标后执行：node scripts/gen-icon-subset.mjs\n */\n` +
    `export const epSubset = ${JSON.stringify(ep.data)} as const\n\n` +
    `export const riSubset = ${JSON.stringify(ri.data)} as const\n`,
  'utf8'
)
console.log(`生成 ${out}`)
console.log(`ep: ${ep.count} 个${ep.missing.length ? '，缺失 ' + ep.missing.join(',') : ''}`)
console.log(`ri: ${ri.count} 个${ri.missing.length ? '，缺失 ' + ri.missing.join(',') : ''}`)
